"""Write every AI prompt, its model settings and its reply schema to prompts/ so they can be read and
reviewed without the code. The code stays the source; tests/test_prompts_export.py fails if the folder
is stale, so after changing a prompt or a setting run:

    python -m app.planner.export_prompts        (from backend/)
"""

import json
from pathlib import Path

import yaml

from app.config import Settings
from app.intake.intake import INTAKE_SYSTEM
from app.models import Meal, MealPlan, MealSpec
from app.planner import llm, prompts
from app.shopping.shopper import MAX_SHORTLIST, MAX_STORES, PICK_SYSTEM, STORE_SYSTEM, Picks, StoreShortlist

OUT = Path(__file__).resolve().parents[3] / "prompts"

# Temperatures each call site passes to LLM.structured (planner.py, intake.py, shopper.py).
TEMPERATURES = {"plan": 0.3, "repair": 0.2, "swap": 0.5, "intake": 0, "store": 0, "pick": 0}

EXAMPLE_SPEC = MealSpec(
    zip_code="61820", days=7, include_snacks=False, macros={"calories": 2000, "protein_g": 110},
    cuisines=["Indian"], protein_source="chicken", allergies=["peanut"], dislikes=["mushrooms"],
    max_prep_minutes=30, effort_level="low_moderate", cooking_skill="basic",
    equipment=["stove", "microwave", "rice_cooker"], budget_weekly_usd=80,
)

README_MD = """# prompts/

The AI side of MealCart, readable without the code. Generated by `backend/app/planner/export_prompts.py`;
`tests/test_prompts_export.py` fails if these files fall behind the code.

| File | What it holds |
|---|---|
| `system_prompts.md` | Every system and user prompt: plan, repair, swap, intake, store shortlist, product picks |
| `model_settings.yaml` | Model order and fallbacks, temperature per task, token caps, timeouts, hedging, call cap |
| `schemas/*.json` | The JSON schema each reply must match (`MealPlan`, `Meal`, `MealSpec`, `StoreShortlist`, `Picks`) |

To change a prompt, edit the code, then run `python -m app.planner.export_prompts` from `backend/`.
"""

PROMPTS_MD = """# MealCart prompts

Generated by `backend/app/planner/export_prompts.py`; do not edit by hand. The code is the source:
`backend/app/planner/prompts.py`, `backend/app/intake/intake.py` and `backend/app/shopping/shopper.py`.

Every call asks for JSON matching a schema in `schemas/`. Replies that don't match are retried once with
the error, then the next model is tried. The model picks foods and products; Python does every number
(portions, macros, pack counts, prices), and `nutrition/validator.py` re-checks every hard rule.

## Planner: system prompt (plan, repair and swap)

Template, filled from the user's request:

```text
{planner_template}
```

Rendered for an example request (7 days, 2000 kcal, 110 g protein, Indian, chicken, peanut allergy,
no mushrooms, 30 minutes, stove + microwave + rice cooker, $80):

```text
{planner_rendered}
```

## Plan: user prompt (schema `MealPlan`)

```text
{plan_user}
```

## Repair: user prompt (schema `MealPlan`)

Sent with the failing days only, each with the validator's problems and its current plan as JSON.

```text
{repair_user}
```

## Swap one meal: user prompt (schema `Meal`)

```text
{swap_user}
```

## Intake: system prompt (schema `MealSpec`)

Turns a request written in words into the same form the page fills in.

```text
{intake}
```

## Store shortlist: system prompt (schema `StoreShortlist`)

The user prompt lists the stores Instacart offers at the delivery address, and the grocery items.

```text
{store}
```

## Product picks: system prompt (schema `Picks`)

The user prompt lists each item with the grams needed and the numbered search results for it.
A pick must be one of those numbers or null, so the model cannot invent a product.

```text
{pick}
```
"""


def _settings() -> dict:
    defaults = {name: f.default for name, f in Settings.model_fields.items()}
    return {
        "models": {
            "primary": defaults["llm_model"],
            "fallbacks": defaults["llm_fallbacks"].split(","),
            "small_tasks_try_first": defaults["llm_short_tasks_first"],
            "providers": sorted(llm.PROVIDERS),
            "note": "Set in .env (LLM_MODEL, LLM_FALLBACKS); entries without a key are skipped.",
        },
        "temperature_by_task": TEMPERATURES,
        "max_reply_tokens": defaults["llm_max_tokens"],
        "max_reply_tokens_by_provider": llm.MAX_TOKENS_BY_PROVIDER,
        "timeouts_s": {
            "long_tasks": defaults["llm_timeout_s"],
            "short_tasks": defaults["llm_short_timeout_s"],
            "hedge_after_long": defaults["llm_hedge_after_s"],
            "hedge_after_short": defaults["llm_hedge_after_short_s"],
            "stall_mid_reply": defaults["llm_stall_s"],
        },
        "long_tasks": sorted(llm.LONG_PURPOSES),
        "max_models_asked_at_once": llm.MAX_PARALLEL,
        "failed_model_cooldown_s": llm.COOLDOWN_S,
        "max_ai_calls_per_run": defaults["llm_max_calls_per_run"],
        "days_per_plan_call": defaults["llm_days_per_call"],
        "shopping": {"stores_shortlisted": MAX_SHORTLIST, "max_stores_per_run": MAX_STORES},
    }


def render() -> dict[str, str]:
    """Every file under prompts/, by relative path."""
    meal = Meal(slot="dinner", title="Chicken curry with rice", prep_minutes=25, ingredients=[], steps=[],
                equipment_used=["stove"])
    plan = MealPlan(days=[])
    files = {
        "README.md": README_MD,
        "system_prompts.md": PROMPTS_MD.format(
            planner_template=prompts.PLANNER_SYSTEM,
            planner_rendered=prompts.planner_system(EXAMPLE_SPEC),
            plan_user=prompts.PLANNER_USER,
            repair_user=prompts.REPAIR_USER,
            swap_user=prompts.swap_user(plan, "Wednesday", meal, "too spicy", 650, 40),
            intake=INTAKE_SYSTEM, store=STORE_SYSTEM, pick=PICK_SYSTEM,
        ),
        "model_settings.yaml": "# Generated by backend/app/planner/export_prompts.py from the code's defaults.\n"
                               + yaml.safe_dump(_settings(), sort_keys=False, allow_unicode=True),
    }
    for name, schema in (("MealSpec", MealSpec), ("MealPlan", MealPlan), ("Meal", Meal),
                         ("StoreShortlist", StoreShortlist), ("Picks", Picks)):
        files[f"schemas/{name}.json"] = json.dumps(schema.model_json_schema(), indent=2) + "\n"
    return files


def main() -> None:
    for rel, text in render().items():
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("wrote", path)


if __name__ == "__main__":
    main()
